// Export preview (UX §11, FR10-04): shows exactly what the file holds (server builds both), then downloads.
import { useCallback, useEffect, useState } from "react";
import { Download } from "lucide-react";
import api from "@/lib/api";
import useUiStore from "@/stores/uiStore";
import Drawer from "@/components/ui/Drawer";
import Skeleton from "@/components/ui/Skeleton";
import ErrorState from "@/components/ui/ErrorState";
import { BTN } from "@/components/ui/buttons";

export default function ExportDrawer({ open, onClose, tab, query, base = "/api/manager/reports" }) {
  const addToast = useUiStore((s) => s.addToast);
  const [doc, setDoc] = useState(null);
  const [error, setError] = useState(null);
  const [busy, setBusy] = useState("");
  const path = `${base}/export?tab=${tab}${query ? `&${query}` : ""}`;

  const load = useCallback(async () => {
    setDoc(null); setError(null);
    try { setDoc(await api.get(`${path}&format=json`)); } catch (e) { setError(e?.message ?? "The preview could not be built."); }
  }, [path]);
  useEffect(() => { if (open) load(); }, [open, load]); // eslint-disable-line react-hooks/set-state-in-effect

  async function download(format) {
    setBusy(format);
    try {
      const blob = await api.download(`${path}&format=${format}`);
      const url = URL.createObjectURL(blob);
      const a = Object.assign(document.createElement("a"), { href: url, download: `achievion-${tab}-${new Date().toISOString().slice(0, 10)}.${format}` });
      document.body.append(a); a.click(); a.remove();
      setTimeout(() => URL.revokeObjectURL(url), 1000);
      addToast({ type: "success", message: `${format.toUpperCase()} downloaded.` });
    } catch (e) { addToast({ type: "error", message: e?.message ?? "The download did not work." }); }
    finally { setBusy(""); }
  }

  return (
    <Drawer open={open} onClose={onClose} title="Export preview" width={720}
      footer={(
        <div className="flex flex-wrap justify-end gap-2">
          <button type="button" className={BTN.ghost} onClick={onClose}>Cancel</button>
          <button type="button" className={BTN.secondary} disabled={!doc || !!busy} onClick={() => download("csv")}>{busy === "csv" ? "Preparing…" : "Download CSV"}</button>
          <button type="button" className={BTN.primary} disabled={!doc || !!busy} onClick={() => download("pdf")}><Download size={15} aria-hidden="true" />{busy === "pdf" ? "Preparing…" : "Download PDF"}</button>
        </div>
      )}>
      {error ? <ErrorState message={error} onRetry={load} /> : !doc ? (
        <div aria-busy="true" aria-label="Building preview" className="flex flex-col gap-3"><Skeleton className="h-8 w-1/2 rounded-lg" /><Skeleton className="h-48 rounded-xl" /></div>
      ) : (
        <article aria-label="PDF preview" className="rounded-xl border border-border-subtle bg-bg-surface p-6 shadow-sm">
          <h3 className="text-lg font-black text-text-primary">{doc.title}</h3>
          <p className="mt-1 text-xs text-text-secondary">{doc.filters}</p>
          <p className="text-xs text-text-secondary">Generated {new Date(doc.generatedAt).toLocaleDateString(undefined, { day: "numeric", month: "long", year: "numeric" })}</p>
          {doc.sections.map((s) => (
            <section key={s.heading} className="mt-5">
              <h4 className="text-sm font-bold text-text-primary">{s.heading}</h4>
              <div className="mt-2 overflow-x-auto">
                <table className="w-full text-left text-xs tabular-nums">
                  <thead><tr>{s.headers.map((h) => <th key={h} scope="col" className="border-b border-ink/[0.08] py-1.5 pr-3 font-bold text-text-secondary">{h}</th>)}</tr></thead>
                  <tbody>
                    {s.rows.length === 0 && <tr><td colSpan={s.headers.length} className="py-2 text-text-secondary">Nothing in this period.</td></tr>}
                    {s.rows.map((r, i) => <tr key={i}>{r.map((c, k) => <td key={k} className="border-b border-ink/[0.04] py-1.5 pr-3 align-top text-text-primary">{c}</td>)}</tr>)}
                  </tbody>
                </table>
              </div>
            </section>
          ))}
          <p className="mt-6 text-center text-[11px] text-text-secondary">Generated by ACHIEVION</p>
        </article>
      )}
    </Drawer>
  );
}
